/*****************************************************************************
 ** \brief	unsigned int sqrt(unsigned long value)
 **			
 ** \param [in] none
 ** \return  none
 ** \note	数字开方根计算
*****************************************************************************/
unsigned int _sqrt(unsigned long value)
{
    unsigned	long T,B,C = 0;
    for (B=0x40000000,T = 0;B != 0;B >>= 2) 
    {
        T = C + B;
        C >>= 1;
        if (T <= value) 
        {
            value -= T;
            C += B;
        }
    }
	C = C & 0xffff;
	return(C);
}


/*****************************************************************************
 ** \brief	unsigned int sqrt(unsigned long value)
 **			
 ** \param [in] none
 ** \return  none
 ** \note	
*****************************************************************************/
unsigned int Sqrt_Q15(signed long value)
{
   unsigned	long C = 0;
   C = _sqrt(value);
   return(C);
}






/*****************************************************************************
 ** \brief	void MC_MotorPower_Calc(void)
 **			
 ** \param [in] none
 ** \return  none
 ** \note	计算电机功率
*****************************************************************************/
void FOC_ThetaLimit(s32 *theta)
{
	if(*theta >= 65535)
		*theta = *theta - 65535;	
	if(*theta < 0)
		*theta = 65535 + *theta;
}



